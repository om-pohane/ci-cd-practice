package com.thinkitive.practice2.service;

import com.thinkitive.practice2.entity.Student;
import com.thinkitive.practice2.repository.StudentRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class StudentService {

    @Autowired
    private StudentRepository studentRepository;

    public Student createStudent(Student student)
    {
        student.setId(null);        // id is generated by the database, ignore any id sent by the client
        student.setDeleted(false);  // a new student is always active
        return studentRepository.save(student);
    }

    public List<Student> getAllStudents()
    {
        return studentRepository.findByDeletedFalse();
    }

    public Student getStudentById(Long id)
    {
        Student student = studentRepository.findByIdAndDeletedFalse(id);
        if (student == null) {
            // Sends a 404 Not Found response to the client
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Student not found with id " + id);
        }
        return student;
    }

    public List<Student> getStudentsByCourse(String course)
    {
        return studentRepository.findByCourseAndDeletedFalse(course);
    }

    public Student updateStudent(Long id, Student newData)
    {
        Student student = getStudentById(id); // throws 404 if not found

        student.setName(newData.getName());
        student.setEmail(newData.getEmail());
        student.setAge(newData.getAge());
        student.setCourse(newData.getCourse());

        return studentRepository.save(student);
    }

    // Soft delete: we don't remove the row, we only mark it as deleted
    public void deleteStudent(Long id)
    {
        Student student = getStudentById(id); // throws 404 if not found
        student.setDeleted(true);
        studentRepository.save(student);
    }

    public List<Student> getDeletedStudents()
    {
        return studentRepository.findByDeletedTrue();
    }

    // Undo the soft delete
    public Student restoreStudent(Long id)
    {
        Student student = studentRepository.findByIdAndDeletedTrue(id);
        if (student == null) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Deleted student not found with id " + id);
        }
        student.setDeleted(false);
        return studentRepository.save(student);
    }
}
